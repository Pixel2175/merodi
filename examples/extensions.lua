-- Markdown extensions.
-- Add an extension here to enable it during parsing.

merodi.extensions.CJK              -- handling of Chinese/Japanese/Korean text spacing
merodi.extensions.DefinitionList   -- support for `Term\n: Definition` lists
merodi.extensions.Footnote         -- support for [^1] style footnotes
merodi.extensions.GFM              -- GitHub-Flavored (tables, strikethrough, autolinks, etc... )
merodi.extensions.Linkify          -- converts bare URLs/emails into clickable links
merodi.extensions.Strikethrough    -- support for ~~struck text~~
merodi.extensions.Table            -- support for markdown tables
merodi.extensions.TaskList         -- support for - [ ] / - [x] checkboxes
merodi.extensions.Typographer      -- turns straight quotes and dashes into typographic ones ("smart quotes")
